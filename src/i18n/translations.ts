export function formatPrice(amount: number, lang: Language): string {
  const localeMap: Record<Language, string> = {
    ca: 'ca-ES',
    es: 'es-ES',
    en: 'en-US',
  };

  return new Intl.NumberFormat(localeMap[lang], {
    style: 'currency',
    currency: 'EUR',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(amount);
}

export function formatInt(num: number, lang: Language): string {
  const localeMap: Record<Language, string> = {
    ca: 'ca-ES',
    es: 'es-ES',
    en: 'en-US',
  };

  return new Intl.NumberFormat(localeMap[lang]).format(num);
}
